import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import assert from 'node:assert/strict'

const root = fileURLToPath(new URL('../', import.meta.url))
const catalog = JSON.parse(readFileSync(path.join(root, 'src/core/capabilities/catalog.json')))
const file = path.join(root, 'package.json')
const manifest = JSON.parse(readFileSync(file))
const tools = catalog.map((d) => ({ name: d.toolName, displayName: d.title, modelDescription: d.description, canBeReferencedInPrompt: true, toolReferenceName: d.toolName.replace('scad_ai_ide_', 'scad_'), inputSchema: d.inputSchema }))
const instructions = [{ path: './instructions/openscad.instructions.md' }]
const skills = ['openscad-runtime', 'openscad-libraries', 'openscad-customizer', 'scad-ai-ide-diagnostics'].map((name) => ({ path: `./skills/${name}/SKILL.md` }))
assert.equal(new Set(tools.map((t) => t.name)).size, tools.length)
for (const asset of [...instructions, ...skills]) {
    const text = readFileSync(path.join(root, asset.path), 'utf8')
    assert.match(text, /^---\nname: .+\ndescription: .+\n/)
    if (asset.path.endsWith('SKILL.md')) assert.match(text, new RegExp(`name: ${path.basename(path.dirname(asset.path))}\\n`))
    for (const name of text.matchAll(/`(scad_ai_ide_\w+)`/g)) assert.ok(tools.some((t) => t.name === name[1]), `Unknown tool in ${asset.path}: ${name[1]}`)
}
for (const source of ['AgentToolAdapter.ts', 'registerAgentTools.ts', 'registerCapabilities.ts']) {
    const code = readFileSync(path.join(root, 'src/features/agents', source), 'utf8')
    assert.doesNotMatch(code, /PanelManager|postMessage|showQuickPick|showOpenDialog|showSaveDialog|showInputBox/, `GUI dependency in ${source}`)
}
const resources = [
    ...instructions.map((resource) => ({ ...resource, kind: 'Instruction' })),
    ...skills.map((resource) => ({ ...resource, kind: 'Skill' })),
].map((resource) => {
    const text = readFileSync(path.join(root, resource.path), 'utf8')
    return { ...resource, name: /^name: (.+)$/m.exec(text)[1], description: /^description: (.+)$/m.exec(text)[1] }
})
const resourceFile = path.join(root, 'src/core/capabilities/resources.json')
const resourceJson = JSON.stringify(resources, null, 2) + '\n'
if (process.argv.includes('--write')) writeFileSync(resourceFile, resourceJson)
else assert.equal(readFileSync(resourceFile, 'utf8'), resourceJson, 'Stale AI Panel resources; run npm run generate:agents')
const guiGroups = JSON.parse(readFileSync(path.join(root, 'src/core/capabilities/gui-actions.json')))
for (const group of guiGroups) {
    const source = readFileSync(path.join(root, group.source), 'utf8')
    const seen = [...new Set([...source.matchAll(new RegExp(group.pattern, 'g'))].map((match) => match[1]))].sort()
    assert.deepEqual(Object.keys(group.actions).sort(), seen, `Unclassified or stale GUI action: ${group.group}`)
    for (const [action, coverage] of Object.entries(group.actions)) {
        assert.ok(coverage.uiOnly || coverage.capabilities?.length, `No classification: ${action}`)
        for (const id of coverage.capabilities ?? []) assert.ok(catalog.some((d) => d.id === id), `Unknown capability ${id} for ${action}`)
    }
}
const testsFor = (d) => d.id.startsWith('runtime.') ? 'runtime.test.ts; capabilityServices.test.ts (all handlers)' : d.id.startsWith('customizer.') ? 'capabilityServices.test.ts; customizer-scrollbar.test.mjs; capabilities.integration.test.ts' : d.id.startsWith('libraries.') ? 'capabilityServices.test.ts (real Library transactions + all handlers); libraries/*.test.ts; libraries.integration.test.ts' : d.id.startsWith('development.') ? 'capabilityServices.test.ts (Production denial; Development cache); libraries.integration.test.ts' : d.id.startsWith('more.') ? 'github.test.ts; capabilities.integration.test.ts; capabilityServices.test.ts' : 'capabilities.test.ts; capabilityServices.test.ts'
const permissionFor = (d) => d.id.startsWith('development.') && d.id !== 'development.status' ? 'Development only; bounded/redacted reads or independent clear confirmation' : d.risk === 'read' ? 'bounded read; live availability' : ['customizer.set', 'customizer.reset', 'customizer.applyPreset', 'operation.cancel'].includes(d.id) ? 'exact target/revision or operation ID' : d.id.startsWith('more.') ? 'interactive VS Code authorization; status only' : 'workspace trust; exact identity/path; independent confirmation for deletion'
const table = `# Agent capability catalog\n\nGenerated by scripts/agent-manifest.mjs. Do not edit; see [audit and verification](agent-capability-matrix.md).\n\n| Capability | Shared handler | GUI entry | Registered Agent Tool | Risk / permissions | Tests |\n|---|---|---|---|---|---|\n` + catalog.map((d) => `| ${d.id} | ${d.service} | ${d.gui} | ${d.toolName} | ${d.risk}; ${permissionFor(d)} | ${testsFor(d)} |`).join('\n') + '\n'
if (process.argv.includes('--write')) {
    manifest.contributes.languageModelTools = tools
    manifest.contributes.chatInstructions = instructions
    manifest.contributes.chatSkills = skills
    writeFileSync(file, JSON.stringify(manifest, null, 4) + '\n')
    writeFileSync(path.join(root, 'docs/agent-capability-catalog.md'), table)
} else {
    assert.deepEqual(manifest.contributes.languageModelTools, tools, 'Stale LM contributions; run npm run generate:agents')
    assert.deepEqual(manifest.contributes.chatInstructions, instructions)
    assert.deepEqual(manifest.contributes.chatSkills, skills)
    assert.equal(readFileSync(path.join(root, 'docs/agent-capability-catalog.md'), 'utf8'), table, 'Stale capability matrix')
}
console.log(`Validated ${tools.length} tools, ${instructions.length} instruction and ${skills.length} skills.`)
