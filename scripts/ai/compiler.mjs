import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, renameSync, rmSync, writeFileSync } from 'node:fs'
import { randomUUID } from 'node:crypto'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { collect, readText } from './collect.mjs'
import { projectCatalog, projectContributions, projectPanel } from './project.mjs'
import { auditGuiParity } from './parity.mjs'

const generated = 'src/ai/generated'
const json = (value, indent = 4) => JSON.stringify(value, null, indent) + '\n'
const banner = '// Generated by scripts/ai/compiler.mjs.\n'

export function compile(root) {
    const { features, bindings, validators, byId } = collect(root)
    const catalog = projectCatalog(features)
    const panel = projectPanel(catalog)
    const manifests = projectContributions(JSON.parse(readText(path.join(root, 'package.json'))), catalog, byId)
    const bindingImports = [...bindings.values()].map((binding, index) => `import { ${binding.export} as tool${index} } from '${path.posix.relative(generated, binding.module).slice(0, -3)}'`)
    const bindingRows = [...bindings.keys()].map((id, index) => `    '${id}': tool${index},`)
    const ids = {
        Feature: features.map((feature) => feature.id),
        Capability: features.filter((feature) => feature.kind === 'tool').map((feature) => feature.tool.capabilityId),
        Group: catalog.groups.map((group) => group.id),
    }
    const index = Object.entries(ids)
        .map(([type, entries]) => `export type ${type}Id = ${entries.map((id) => JSON.stringify(id)).join(' | ') || 'never'}\n`)
        .join('')
    const docs =
        '# Agent capability catalog\n\nGenerated by scripts/ai/compiler.mjs. See the [verification matrix](agent-capability-matrix.md).\n\n' +
        '| Capability | Shared handler | GUI entry | Agent Tool | Risk | Workspace Trust |\n|---|---|---|---|---|---|\n' +
        features
            .filter((feature) => feature.kind === 'tool')
            .map(({ tool, requiresTrust }) => `| ${tool.capabilityId} | ${tool.service} | ${tool.gui} | ${tool.name} | ${tool.risk} | ${requiresTrust ? 'Required' : 'Independent'} |\n`)
            .join('')
    return {
        'package.json': json(manifests),
        [generated + '/feature-catalog.generated.json']: json(catalog),
        [generated + '/feature-bindings.generated.ts']: banner + "import type { ToolHandler } from '../contracts/ToolServices'\nimport type { CapabilityId } from './feature-ids.generated'\n" + bindingImports.join('\n') + '\n\nexport const toolBindings = {\n' + bindingRows.join('\n') + '\n} satisfies Record<CapabilityId, ToolHandler>\n',
        [generated + '/feature-ids.generated.ts']: banner + index,
        [generated + '/ai-panel-layout.generated.json']: json(panel.layout),
        [generated + '/ai-panel-state.schema.json']: json(panel.panelState),
        [generated + '/ai-preferences.schema.json']: json(panel.preferences),
        'docs/agent-capability-catalog.md': docs,
        'docs/gui-agent-parity.md': auditGuiParity(root, validators),
    }
}

export function checkOutputs(root, output, write) {
    const stale = []
    for (const [relative, content] of Object.entries(output)) {
        const file = path.join(root, relative)
        const before = existsSync(file) ? readText(file) : undefined
        if (before === content) continue
        if (!write) {
            const lines = before?.split('\n') ?? []
            const generatedLines = content.split('\n')
            const first = generatedLines.findIndex((line, index) => line !== lines[index])
            stale.push(`${relative} (line ${first + 1}: ${generatedLines[first]?.trim() ?? 'output length changed'})`)
            continue
        }
        mkdirSync(path.dirname(file), { recursive: true })
        const temp = file + '.' + randomUUID() + '.tmp'
        try {
            writeFileSync(temp, content, { flag: 'wx' })
            renameSync(temp, file)
        } finally {
            rmSync(temp, { force: true })
        }
    }
    if (stale.length) throw new Error('Stale AI feature outputs. Run npm run generate:agents:\n' + stale.join('\n'))
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
    const root = fileURLToPath(new URL('../../', import.meta.url))
    const write = process.argv[2] === '--write'
    if (!write && process.argv[2] !== '--check') throw new Error('Expected --check or --write')
    if (write) execFileSync(process.execPath, [path.join(root, 'scripts/assert-feature-branch.mjs')], { cwd: root, stdio: 'inherit' })
    const output = compile(root)
    checkOutputs(root, output, write)
    const catalog = JSON.parse(output[generated + '/feature-catalog.generated.json'])
    const count = (kind) => catalog.features.filter((feature) => feature.kind === kind).length
    console.log(`Validated ${count('tool')} tools, ${count('skill')} skills and ${count('instruction')} instructions with GUI parity.`)
}
