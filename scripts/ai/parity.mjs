import assert from 'node:assert/strict'
import path from 'node:path'
import { readText } from './collect.mjs'

export function auditGuiParity(root, validators) {
    const guiGroups = JSON.parse(readText(path.join(root, 'src/core/capabilities/gui-actions.json')))
    for (const group of guiGroups) {
        const source = readText(path.join(root, group.source), 'utf8')
        const seen = [...new Set([...source.matchAll(new RegExp(group.pattern, 'g'))].map((match) => match[1]))].sort()
        assert.deepEqual(Object.keys(group.actions).sort(), seen, `Unclassified or stale GUI action: ${group.group}`)
        for (const [action, coverage] of Object.entries(group.actions)) {
            assert.ok(coverage.uiOnly || coverage.capabilities?.length, `No classification: ${action}`)
            for (const id of coverage.capabilities ?? []) assert.ok(validators.has(id), `Unknown capability ${id} for ${action}`)
            if (!coverage.uiOnly) {
                assert.ok(coverage.examples?.length, `Missing executable Agent input contract for ${group.group}/${action}`)
                assert.deepEqual([...new Set(coverage.examples.map((e) => e.capability))].sort(), [...coverage.capabilities].sort(), `Incomplete Agent input contracts: ${group.group}/${action}`)
                for (const example of coverage.examples) {
                    const validate = validators.get(example.capability)
                    assert.ok(validate?.(example.input), `Invalid Agent input for ${group.group}/${action}: ${JSON.stringify(validate?.errors)}`)
                }
            }
        }
    }
    const parityTable = '# GUI and Agent business parity\n\nGenerated by scripts/ai/compiler.mjs from the audited GUI actions and schema-checked Agent input contracts. Scope: Runtime, Customizer, Libraries, More and CAD diagnostics and raw mesh verification. Mesh measurements and frozen CLI images share snapshot-bound services; static declared-part assembly shares these services; scene editing and slicer integration remain deferred. GUI navigation/presentation is classified separately below. Schema checks establish valid calls; behavioral and model acceptance are separate (see agent-verification.md).\n\n| GUI area | Action | Agent capability | Example input |\n|---|---|---|---|\n' + guiGroups.flatMap((group) => Object.entries(group.actions).flatMap(([action, coverage]) => (coverage.uiOnly ? [`| ${group.group} | ${action} | Presentation | ${coverage.uiOnly} |`] : coverage.examples.map((e) => `| ${group.group} | ${action} | ${e.capability} | \`${JSON.stringify(e.input)}\` |`)))).join('\n') + '\n'
    return parityTable
}
